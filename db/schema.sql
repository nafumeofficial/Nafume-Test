-- ============================================================================
-- NAFUME — Customer & Commerce Database Schema
-- ----------------------------------------------------------------------------
-- Target: PostgreSQL 14+ (written for Supabase, but plain Postgres works too).
--
-- HOW TO APPLY
--   NEW, EMPTY database: Supabase → SQL Editor → New query → paste this file →
--   Run. It includes every migration in db/migrations/.
--   EXISTING database that already holds data: do NOT re-run this whole file.
--   Apply only the migrations in db/migrations/ you have not applied yet (check
--   the schema_migrations table), after taking a backup.
--   Every statement is guarded (IF NOT EXISTS / DO-blocks) and nothing here
--   drops or truncates data.
--
-- SECURITY MODEL
--   Row Level Security is ENABLED on every table and NO policies are created.
--   With RLS on and no policies, the public `anon` key can read/write nothing.
--   All access goes through the Vercel serverless functions in /api, which use
--   SUPABASE_SERVICE_ROLE_KEY (bypasses RLS) and never expose it to the browser.
--   Do NOT add permissive policies unless you have thought hard about them.
--
-- CONVENTIONS
--   * Primary keys are UUIDs generated by the application (api/_lib/db.js newId)
--     so a row's id is known before insert and both storage drivers behave the
--     same way.
--   * Money is stored in whole rupees (INTEGER). NAFUME prices are whole rupees
--     and integer arithmetic avoids float rounding on totals.
--   * `*_normalized` columns are the matching keys: lowercased/trimmed email and
--     last-10-digits phone. Uniqueness is enforced on those, not on raw input.
-- ============================================================================

-- ── customers ───────────────────────────────────────────────────────────────
-- One row per human. Created by checkout (guest) or by account registration.
-- Matched on normalized email OR normalized phone so repeat buyers do not
-- accumulate duplicate rows.
CREATE TABLE IF NOT EXISTS customers (
  id                UUID PRIMARY KEY,
  name              TEXT,
  email             TEXT,
  email_normalized  TEXT,
  phone             TEXT,
  phone_normalized  TEXT,
  address_line1     TEXT,
  address_line2     TEXT,
  city              TEXT,
  state             TEXT,
  pincode           TEXT,
  country           TEXT        NOT NULL DEFAULT 'India',
  has_account       BOOLEAN     NOT NULL DEFAULT FALSE,
  source            TEXT        NOT NULL DEFAULT 'checkout',
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Partial unique indexes: NULL identifiers never collide, so a phone-only
-- customer and an email-only customer can coexist.
CREATE UNIQUE INDEX IF NOT EXISTS customers_email_normalized_key
  ON customers (email_normalized) WHERE email_normalized IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS customers_phone_normalized_key
  ON customers (phone_normalized) WHERE phone_normalized IS NOT NULL;
CREATE INDEX IF NOT EXISTS customers_created_at_idx ON customers (created_at DESC);

-- ── customer_auth ───────────────────────────────────────────────────────────
-- Password credentials, split from `customers` so a plain checkout customer
-- (no account) never has a credentials row at all.
-- password_hash format:  scrypt$N$r$p$<salt-b64>$<hash-b64>   (see api/_lib/auth.js)
-- Plaintext passwords are never stored, logged, or returned by any endpoint.
CREATE TABLE IF NOT EXISTS customer_auth (
  id              UUID PRIMARY KEY,
  customer_id     UUID        NOT NULL UNIQUE REFERENCES customers(id) ON DELETE CASCADE,
  password_hash   TEXT        NOT NULL,
  failed_attempts INTEGER     NOT NULL DEFAULT 0,
  locked_until    TIMESTAMPTZ,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ── sessions ────────────────────────────────────────────────────────────────
-- Server-side sessions. Only the SHA-256 hash of the token is stored, so a
-- database leak does not hand out live sessions. Revocable (logout).
CREATE TABLE IF NOT EXISTS sessions (
  id          UUID PRIMARY KEY,
  customer_id UUID        NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  token_hash  TEXT        NOT NULL UNIQUE,
  method      TEXT        NOT NULL DEFAULT 'password',   -- 'password' | 'otp'
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at  TIMESTAMPTZ NOT NULL,
  revoked_at  TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS sessions_customer_idx ON sessions (customer_id);
CREATE INDEX IF NOT EXISTS sessions_expires_idx  ON sessions (expires_at);

-- ── orders ──────────────────────────────────────────────────────────────────
-- The authoritative order record. Written pending at Razorpay-order creation,
-- promoted to paid only after server-side signature + payment verification.
--
-- IDEMPOTENCY (critical): razorpay_payment_id is UNIQUE. A duplicate verify
-- callback, a refresh, or a browser retry can therefore never create a second
-- paid order — the second insert/update is a no-op that resolves to the same
-- row. razorpay_order_id is UNIQUE for the same reason one level up.
CREATE TABLE IF NOT EXISTS orders (
  id                    UUID PRIMARY KEY,
  order_id              TEXT        NOT NULL UNIQUE,          -- public NF-xxxxxx-nnn id
  customer_id           UUID        REFERENCES customers(id) ON DELETE SET NULL,

  razorpay_order_id     TEXT,
  razorpay_payment_id   TEXT,
  razorpay_signature    TEXT,

  currency              TEXT        NOT NULL DEFAULT 'INR',
  amount_subtotal       INTEGER     NOT NULL DEFAULT 0,
  amount_bundle_discount INTEGER    NOT NULL DEFAULT 0,
  amount_prepaid_discount INTEGER   NOT NULL DEFAULT 0,
  amount_gift_addon     INTEGER     NOT NULL DEFAULT 0,
  amount_shipping       INTEGER     NOT NULL DEFAULT 0,
  -- Promo code applied to this order, and the rupees it took off. The code is
  -- stored on the order as well as in discount_redemptions so an order can be
  -- read back and explained without a join.
  discount_code         TEXT,
  amount_discount       INTEGER     NOT NULL DEFAULT 0,
  amount_total          INTEGER     NOT NULL DEFAULT 0,

  payment_status        TEXT        NOT NULL DEFAULT 'pending',      -- pending | paid | failed
  order_status          TEXT        NOT NULL DEFAULT 'created',      -- created | confirmed | cancelled
  fulfillment_status    TEXT        NOT NULL DEFAULT 'unfulfilled',  -- unfulfilled | shipped | delivered
  payment_method        TEXT        NOT NULL DEFAULT 'razorpay',
  checkout_type         TEXT        NOT NULL DEFAULT 'razorpay',

  ship_name             TEXT,
  ship_phone            TEXT,
  ship_email            TEXT,
  ship_line1            TEXT,
  ship_line2            TEXT,
  ship_city             TEXT,
  ship_state            TEXT,
  ship_pincode          TEXT,
  ship_country          TEXT        NOT NULL DEFAULT 'India',

  whatsapp_opt_in       BOOLEAN     NOT NULL DEFAULT FALSE,
  notes                 TEXT,
  offers                JSONB       NOT NULL DEFAULT '[]'::jsonb,

  -- Fulfilment / delivery (Phase 6 depends on delivered_at being set)
  shipped_at            TIMESTAMPTZ,
  delivered_at          TIMESTAMPTZ,
  courier_name          TEXT,
  awb                   TEXT,

  -- Review-request lifecycle
  review_request_status TEXT        NOT NULL DEFAULT 'not_due',      -- not_due | queued | sent | skipped
  review_requested_at   TIMESTAMPTZ,
  review_id             UUID,

  paid_at               TIMESTAMPTZ,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS orders_razorpay_payment_id_key
  ON orders (razorpay_payment_id) WHERE razorpay_payment_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS orders_razorpay_order_id_key
  ON orders (razorpay_order_id) WHERE razorpay_order_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS orders_customer_idx      ON orders (customer_id);
CREATE INDEX IF NOT EXISTS orders_created_idx       ON orders (created_at DESC);
CREATE INDEX IF NOT EXISTS orders_ship_email_idx    ON orders (ship_email);
CREATE INDEX IF NOT EXISTS orders_ship_phone_idx    ON orders (ship_phone);
CREATE INDEX IF NOT EXISTS orders_delivered_idx     ON orders (delivered_at)
  WHERE delivered_at IS NOT NULL;

-- ── order_items ─────────────────────────────────────────────────────────────
-- Line items snapshotted at purchase time. Prices are the SERVER's prices, not
-- anything the browser sent.
CREATE TABLE IF NOT EXISTS order_items (
  id           UUID PRIMARY KEY,
  order_uuid   UUID        NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  order_id     TEXT        NOT NULL,
  product_id   TEXT        NOT NULL,
  product_name TEXT        NOT NULL,
  unit_price   INTEGER     NOT NULL,
  quantity     INTEGER     NOT NULL,
  line_total   INTEGER     NOT NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS order_items_order_idx    ON order_items (order_uuid);
CREATE INDEX IF NOT EXISTS order_items_order_id_idx ON order_items (order_id);

-- ── leads ───────────────────────────────────────────────────────────────────
-- Email captured WITHOUT a purchase (exit-intent popup, quiz). A lead is NOT a
-- customer and must never be counted as one.
-- UNIQUE(email_normalized, source): one lead row per email per capture surface,
-- so a repeat popup submission updates rather than duplicating.
CREATE TABLE IF NOT EXISTS leads (
  id               UUID PRIMARY KEY,
  email            TEXT        NOT NULL,
  email_normalized TEXT        NOT NULL,
  source           TEXT        NOT NULL,             -- popup_lead | fragrance_quiz
  discount_code    TEXT,
  discount_label   TEXT,
  metadata         JSONB       NOT NULL DEFAULT '{}'::jsonb,
  converted_at     TIMESTAMPTZ,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS leads_email_source_key
  ON leads (email_normalized, source);
CREATE INDEX IF NOT EXISTS leads_created_idx ON leads (created_at DESC);

-- ── marketing_consent ───────────────────────────────────────────────────────
-- Explicit, per-channel, timestamped consent with its capture source. Kept
-- separate from `orders` so transactional messaging (order updates, which do
-- not need marketing consent) stays distinct from marketing broadcast
-- eligibility. Only rows with opted_in = TRUE may be exported to a broadcast
-- tool.
CREATE TABLE IF NOT EXISTS marketing_consent (
  id             UUID PRIMARY KEY,
  customer_id    UUID        NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  channel        TEXT        NOT NULL,               -- whatsapp | email
  opted_in       BOOLEAN     NOT NULL DEFAULT FALSE,
  consent_source TEXT        NOT NULL,               -- checkout | popup | quiz | account
  consent_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  revoked_at     TIMESTAMPTZ,
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS marketing_consent_customer_channel_key
  ON marketing_consent (customer_id, channel);

-- ── quiz_responses ──────────────────────────────────────────────────────────
-- Fragrance-finder answers + the recommendation shown. preference_tags is the
-- segmentation key (e.g. {oud,evening,strong}) used to target campaigns.
CREATE TABLE IF NOT EXISTS quiz_responses (
  id                   UUID PRIMARY KEY,
  email                TEXT,
  email_normalized     TEXT,
  customer_id          UUID        REFERENCES customers(id) ON DELETE SET NULL,
  lead_id              UUID        REFERENCES leads(id) ON DELETE SET NULL,
  answers              JSONB       NOT NULL DEFAULT '{}'::jsonb,
  recommended_product_id   TEXT,
  recommended_product_name TEXT,
  alternate_product_id TEXT,
  preference_tags      JSONB       NOT NULL DEFAULT '[]'::jsonb,
  source               TEXT        NOT NULL DEFAULT 'fragrance_quiz',
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS quiz_email_idx   ON quiz_responses (email_normalized);
CREATE INDEX IF NOT EXISTS quiz_created_idx ON quiz_responses (created_at DESC);

-- ── reviews ─────────────────────────────────────────────────────────────────
-- UNIQUE(order_id, product_id) stops a customer submitting the same product
-- twice for the same order. order_id NULL is allowed (unverified review) and
-- NULLs do not collide, matching Postgres UNIQUE semantics.
CREATE TABLE IF NOT EXISTS reviews (
  id             UUID PRIMARY KEY,
  order_id       TEXT,
  order_uuid     UUID        REFERENCES orders(id) ON DELETE SET NULL,
  customer_id    UUID        REFERENCES customers(id) ON DELETE SET NULL,
  product_id     TEXT        NOT NULL,
  product_name   TEXT,
  rating         INTEGER     NOT NULL CHECK (rating BETWEEN 1 AND 5),
  title          TEXT,
  body           TEXT,
  photo_data_url TEXT,                                -- small inline image, validated server-side
  author_name    TEXT,
  author_email   TEXT,
  verified       BOOLEAN     NOT NULL DEFAULT FALSE,
  status         TEXT        NOT NULL DEFAULT 'pending',   -- pending | published | hidden
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS reviews_order_product_key
  ON reviews (order_id, product_id) WHERE order_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS reviews_product_idx ON reviews (product_id, status);

-- ── review_requests ─────────────────────────────────────────────────────────
-- One scheduling row per order. UNIQUE(order_id) means the scheduler running
-- twice cannot queue two requests for the same order.
CREATE TABLE IF NOT EXISTS review_requests (
  id            UUID PRIMARY KEY,
  order_id      TEXT        NOT NULL UNIQUE,
  order_uuid    UUID        REFERENCES orders(id) ON DELETE CASCADE,
  customer_id   UUID        REFERENCES customers(id) ON DELETE SET NULL,
  channel       TEXT        NOT NULL DEFAULT 'email',     -- email | whatsapp
  scheduled_for TIMESTAMPTZ NOT NULL,
  status        TEXT        NOT NULL DEFAULT 'queued',    -- queued | sent | failed | skipped
  attempts      INTEGER     NOT NULL DEFAULT 0,
  last_error    TEXT,
  sent_at       TIMESTAMPTZ,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS review_requests_due_idx ON review_requests (status, scheduled_for);

-- ── outbound_messages ───────────────────────────────────────────────────────
-- Durable outbox. Every customer-facing email/WhatsApp message is recorded here
-- FIRST, then a provider attempt updates it. When no provider is configured the
-- row simply stays 'queued' — the system never reports a send that did not
-- happen, and nothing is lost when credentials are added later.
CREATE TABLE IF NOT EXISTS outbound_messages (
  id                  UUID PRIMARY KEY,
  channel             TEXT        NOT NULL,            -- email | whatsapp
  to_address          TEXT        NOT NULL,
  subject             TEXT,
  body                TEXT,
  status              TEXT        NOT NULL DEFAULT 'queued',  -- queued | sent | failed
  provider            TEXT,
  provider_message_id TEXT,
  error               TEXT,
  related_type        TEXT,                            -- order | review_request | lead | quiz
  related_id          TEXT,
  attempts            INTEGER     NOT NULL DEFAULT 0,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  sent_at             TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS outbound_status_idx ON outbound_messages (status, created_at);

-- ── discount_redemptions ────────────────────────────────────────────────────
-- One row per (code, order). Written when the order is created — before
-- payment — so a discount is always traceable to a real order rather than
-- floating free.
--
-- status:
--   pending   order exists, not yet committed. Counts against the customer's
--             allowance only while the order is fresh (see HOLD_MINUTES in
--             api/_lib/discounts.js), so an abandoned checkout does not burn
--             someone's discount forever.
--   redeemed  the order was paid (or is a confirmed COD order).
--   released  the order was cancelled; the allowance goes back.
--
-- UNIQUE(code, order_id) is what makes a retried or replayed order-creation a
-- no-op instead of a second consumption.
CREATE TABLE IF NOT EXISTS discount_redemptions (
  id              UUID PRIMARY KEY,
  code            TEXT        NOT NULL,
  customer_id     UUID        REFERENCES customers(id) ON DELETE SET NULL,
  order_id        TEXT        NOT NULL,
  order_uuid      UUID        REFERENCES orders(id) ON DELETE CASCADE,
  review_id       UUID        REFERENCES reviews(id) ON DELETE SET NULL,
  subtotal_before INTEGER     NOT NULL DEFAULT 0,
  discount_amount INTEGER     NOT NULL DEFAULT 0,
  final_amount    INTEGER     NOT NULL DEFAULT 0,
  status          TEXT        NOT NULL DEFAULT 'pending',   -- pending | redeemed | released
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  redeemed_at     TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS discount_redemptions_code_order_key
  ON discount_redemptions (code, order_id);
CREATE INDEX IF NOT EXISTS discount_redemptions_customer_idx
  ON discount_redemptions (customer_id, code);
CREATE INDEX IF NOT EXISTS discount_redemptions_status_idx
  ON discount_redemptions (status, created_at);

-- ── rate_limits ─────────────────────────────────────────────────────────────
-- Durable, cross-instance throttling for sensitive endpoints. Serverless spreads
-- requests across instances, so an in-memory counter only ever sees a fraction
-- of the traffic; this table is shared by all of them.
--
-- One row per (bucket, window). `bucket` already encodes the scope — e.g.
-- "login|203.0.113.9" or "otp-send|9876543210" — so a single unique index does
-- all the work, and expired rows are swept opportunistically.
CREATE TABLE IF NOT EXISTS rate_limits (
  id           UUID PRIMARY KEY,
  bucket       TEXT        NOT NULL,
  window_start TIMESTAMPTZ NOT NULL,
  window_end   TIMESTAMPTZ NOT NULL,
  hits         INTEGER     NOT NULL DEFAULT 1,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS rate_limits_bucket_window_key
  ON rate_limits (bucket, window_start);
CREATE INDEX IF NOT EXISTS rate_limits_expiry_idx ON rate_limits (window_end);

-- ── Row Level Security: on everywhere, no policies anywhere ─────────────────
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'customers','customer_auth','sessions','orders','order_items','leads',
    'marketing_consent','quiz_responses','reviews','review_requests','outbound_messages',
    'discount_redemptions','rate_limits'
  ] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;

