/*
 * server/_lib/db-d1.js  —  Cloudflare D1 (SQLite) storage driver
 * ============================================================================
 * Implements the same four operations as the other drivers in db.js
 * (select / insert / update / count) on top of a D1 binding, or anything that
 * exposes the same prepare().bind().all() / batch() surface (the test suite
 * uses a node:sqlite shim, see test/d1-shim.js).
 *
 * Mapping to the Postgres behaviour the endpoints were written against:
 *   * BOOLEAN columns are stored 0/1 and returned as true/false.
 *   * JSONB columns are stored as JSON text and returned as parsed values.
 *   * Timestamps are ISO-8601 strings (generated by the app), compared as text.
 *   * "ORDER BY ... NULLS LAST" is emulated for both directions.
 *   * update() is one UPDATE ... RETURNING statement, so a conditional update
 *     ("set paid WHERE payment_status = pending") stays atomic: exactly one
 *     concurrent caller gets the row back.
 *   * A UNIQUE failure becomes UniqueViolationError, as with Postgres 23505.
 *
 * Identifiers (table and column names) are checked against the schema's table
 * list and a strict pattern before they reach SQL; every value is bound.
 */
"use strict";

const BOOL_COLS = new Set(["has_account", "whatsapp_opt_in", "opted_in", "verified"]);
const JSON_COLS = new Set(["offers", "metadata", "answers", "preference_tags", "payload"]);
const IDENT     = /^[A-Za-z_][A-Za-z0-9_]*$/;

function createD1Driver(binding, deps) {
  const DbError              = deps.DbError;
  const UniqueViolationError = deps.UniqueViolationError;
  const normalizeCondition   = deps.normalizeCondition;
  const TABLES               = deps.TABLES;

  function table(name) {
    if (TABLES.indexOf(name) === -1 && name !== "schema_migrations") throw new DbError("Unknown table: " + name);
    return '"' + name + '"';
  }
  function col(name) {
    if (!IDENT.test(String(name))) throw new DbError("Invalid column name.");
    return '"' + name + '"';
  }

  /* JS value -> bindable SQLite value for column `c`. */
  function toDb(c, v) {
    if (v === undefined) return null;
    if (v === null) return null;
    if (BOOL_COLS.has(c)) return v ? 1 : 0;
    if (JSON_COLS.has(c)) return typeof v === "string" ? v : JSON.stringify(v);
    if (typeof v === "boolean") return v ? 1 : 0;
    if (v instanceof Date) return v.toISOString();
    if (typeof v === "object") return JSON.stringify(v);
    return v;
  }

  /* SQLite row -> the shape the endpoints expect. */
  function fromDb(row) {
    if (!row) return row;
    const out = {};
    Object.keys(row).forEach(function (k) {
      let v = row[k];
      if (v !== null && v !== undefined) {
        if (BOOL_COLS.has(k)) v = v === 1 || v === true || v === "1";
        else if (JSON_COLS.has(k) && typeof v === "string") {
          try { v = JSON.parse(v); } catch (_) { /* leave as text */ }
        }
      }
      out[k] = v;
    });
    return out;
  }

  function buildWhere(where, params) {
    const parts = [];
    Object.keys(where || {}).forEach(function (c) {
      const cond = normalizeCondition(where[c]);
      const name = col(c);
      switch (cond.op) {
        case "eq":
          if (cond.value === null) { parts.push(name + " IS NULL"); break; }
          parts.push(name + " = ?"); params.push(toDb(c, cond.value)); break;
        case "neq":
          parts.push(name + " <> ?"); params.push(toDb(c, cond.value)); break;
        case "gt":  parts.push(name + " > ?");  params.push(toDb(c, cond.value)); break;
        case "gte": parts.push(name + " >= ?"); params.push(toDb(c, cond.value)); break;
        case "lt":  parts.push(name + " < ?");  params.push(toDb(c, cond.value)); break;
        case "lte": parts.push(name + " <= ?"); params.push(toDb(c, cond.value)); break;
        case "is":
          if (cond.value === null) parts.push(name + " IS NULL");
          else { parts.push(name + " IS ?"); params.push(toDb(c, cond.value)); }
          break;
        case "in": {
          const list = Array.isArray(cond.value) ? cond.value : [cond.value];
          if (!list.length) { parts.push("0"); break; }
          parts.push(name + " IN (" + list.map(function () { return "?"; }).join(",") + ")");
          list.forEach(function (v) { params.push(toDb(c, v)); });
          break;
        }
        case "like":
        case "ilike":
          parts.push(name + " LIKE ?"); params.push(String(cond.value)); break;
        default:
          throw new DbError("Unsupported operator: " + cond.op);
      }
    });
    return parts.length ? " WHERE " + parts.join(" AND ") : "";
  }

  function columnsClause(columns) {
    if (!columns || columns === "*") return "*";
    return String(columns).split(",").map(function (c) { return col(c.trim()); }).join(", ");
  }

  function mapError(err, tableName) {
    const msg = String((err && err.message) || err || "");
    const m = /UNIQUE constraint failed:\s*([^\n:]+)/i.exec(msg);
    if (m) {
      const first = m[1].split(",")[0].trim();           // "orders.order_id"
      return new UniqueViolationError(tableName, first.indexOf(".") !== -1 ? first : tableName + "_" + first);
    }
    if (/FOREIGN KEY constraint failed/i.test(msg)) return new DbError("Database request failed.", 409, "foreign_key_violation");
    return new DbError(
      /timeout|network|unreachable/i.test(msg) ? "Database is unreachable." : "Database request failed.",
      0, msg.slice(0, 200));
  }


  /* prepared-statement helper that keeps `bind` bound to its own statement */
  function stmt(sql, params) {
    const s = binding.prepare(sql);
    return params.length ? s.bind.apply(s, params) : s;
  }
  async function run(sql, params, tableName) {
    try {
      const res = await stmt(sql, params).all();
      return (res && res.results) || [];
    } catch (err) { throw mapError(err, tableName); }
  }

  return {
    name: "d1",
    isConfigured: function () { return true; },

    select: async function (name, opts) {
      opts = opts || {};
      const params = [];
      let sql = "SELECT " + columnsClause(opts.columns) + " FROM " + table(name) + buildWhere(opts.where, params);
      if (opts.order) {
        const c = col(opts.order.column);
        sql += " ORDER BY " + c + " IS NULL, " + c + (opts.order.ascending === false ? " DESC" : " ASC");
      }
      if (opts.limit) sql += " LIMIT " + parseInt(opts.limit, 10);
      return (await run(sql, params, name)).map(fromDb);
    },

    insert: async function (name, rowOrRows, opts) {
      opts = opts || {};
      const rows = Array.isArray(rowOrRows) ? rowOrRows : [rowOrRows];
      if (!rows.length) return [];

      const statements = rows.map(function (row) {
        const cols = Object.keys(row).filter(function (c) { return row[c] !== undefined; });
        const params = cols.map(function (c) { return toDb(c, row[c]); });
        let verb = "INSERT";
        let tail = "";
        if (opts.ignoreDuplicates) verb = "INSERT OR IGNORE";
        else if (opts.mergeDuplicates && opts.onConflict) {
          const target = String(opts.onConflict).split(",").map(function (c) { return col(c.trim()); }).join(", ");
          const sets = cols.map(function (c) { return col(c) + " = excluded." + col(c); }).join(", ");
          tail = " ON CONFLICT (" + target + ") DO UPDATE SET " + sets;
        }
        const sql = verb + " INTO " + table(name) + " (" + cols.map(col).join(", ") + ") VALUES (" +
                    cols.map(function () { return "?"; }).join(", ") + ")" + tail + " RETURNING *";
        return stmt(sql, params);
      });

      try {
        // batch() runs the statements in one implicit transaction: all rows or none.
        const results = statements.length === 1
          ? [await statements[0].all()]
          : await binding.batch(statements);
        const out = [];
        results.forEach(function (r) { ((r && r.results) || []).forEach(function (x) { out.push(fromDb(x)); }); });
        return out;
      } catch (err) { throw mapError(err, name); }
    },

    update: async function (name, opts) {
      opts = opts || {};
      const set = opts.set || {};
      const cols = Object.keys(set).filter(function (c) { return set[c] !== undefined; });
      if (!cols.length) return [];
      const params = cols.map(function (c) { return toDb(c, set[c]); });
      const sql = "UPDATE " + table(name) + " SET " +
        cols.map(function (c) { return col(c) + " = ?"; }).join(", ") +
        buildWhere(opts.where, params) + " RETURNING *";
      return (await run(sql, params, name)).map(fromDb);
    },

    count: async function (name, opts) {
      const params = [];
      const sql = "SELECT COUNT(*) AS n FROM " + table(name) + buildWhere((opts || {}).where, params);
      const rows = await run(sql, params, name);
      return rows.length ? Number(rows[0].n) : 0;
    }
  };
}

module.exports = { createD1Driver };
